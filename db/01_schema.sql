-- 01_schema.sql
-- สร้างตารางของแอป Reamo ใน Supabase (สคีมา public)
--
-- ข้อกำหนดก่อนรัน:
--   * ต้องมีตาราง public.profiles อยู่แล้ว (สร้างโดยทีม backend, id = auth.users.id)
--   * รันใน SQL Editor ของ Supabase ทั้งไฟล์ในครั้งเดียว
--   * ห่อด้วย transaction: ถ้ามีคำสั่งใดพลาด ทุกอย่างจะถูกยกเลิก
--   * รันซ้ำไม่ได้ (create type / create table จะ error ถ้ามีอยู่แล้ว)
--
-- หมายเหตุพฤติกรรมตอนลบ:
--   * ลบ profile -> ข้อมูลส่วนตัว (user_books, shelves, memories, shelf_items,
--     recommendations) ถูกลบตาม (cascade)
--   * ลบ profile -> books.created_by กลายเป็น null แต่หนังสือยังอยู่
--   * ลบ book ที่ถูกอ้างอิงโดย user_books / recommendations ไม่ได้ (ฐานข้อมูลปฏิเสธ)

begin;

create type public.reading_status as enum
  ('want_to_read', 'reading', 'finished');

-- หนังสือ: เก็บครั้งเดียว ใช้ร่วมกันทุกคน
-- created_by = ผู้สร้าง (แก้/ลบได้เฉพาะคนนี้ ตรวจในโค้ด backend)
create table public.books (
  id integer generated by default as identity primary key,
  title text not null,
  author text,
  isbn text unique,
  cover_url text,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

-- รายการความรู้สึก (tag ให้ผู้ใช้เลือก) ใส่ข้อมูลตั้งต้นใน 03_seed_feelings.sql
create table public.feelings (
  id integer generated by default as identity primary key,
  slug text not null unique,
  name_en text not null,
  name_th text not null
);

-- หนังสือของฉัน: หนึ่งแถวต่อ (คน, เล่ม) เก็บสถานะการอ่าน
create table public.user_books (
  id integer generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  book_id integer not null references public.books(id),
  status public.reading_status default 'finished',
  created_at timestamptz not null default now(),
  unique (user_id, book_id)
);

-- ความทรงจำ: ผูกกับ "หนังสือของฉัน"
create table public.memories (
  id integer generated by default as identity primary key,
  user_book_id integer not null references public.user_books(id) on delete cascade,
  body text not null,
  moment text,
  is_public boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ชั้นหนังสือ
create table public.shelves (
  id integer generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  name text not null,
  description text,
  is_public boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- หนังสือเล่มไหนอยู่บนชั้นไหน
create table public.shelf_items (
  id integer generated by default as identity primary key,
  shelf_id integer not null references public.shelves(id) on delete cascade,
  user_book_id integer not null references public.user_books(id) on delete cascade,
  position integer,
  added_at timestamptz not null default now(),
  unique (shelf_id, user_book_id)
);

-- คำแนะนำ: (ผู้ใช้, หนังสือ, ความรู้สึก) + เหตุผลที่ผู้ใช้เขียนเอง
create table public.recommendations (
  id integer generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  book_id integer not null references public.books(id),
  feeling_id integer not null references public.feelings(id),
  reason text not null,
  created_at timestamptz not null default now(),
  unique (user_id, book_id, feeling_id)
);

create index on public.books (created_by);
create index on public.user_books (book_id);
create index on public.memories (user_book_id);
create index on public.shelves (user_id);
create index on public.shelf_items (user_book_id);
create index on public.recommendations (feeling_id, book_id);

-- เปิด RLS ทุกตาราง (ยังไม่มี policy = ปฏิเสธทุกแถวสำหรับ anon/authenticated)
alter table public.books enable row level security;
alter table public.feelings enable row level security;
alter table public.user_books enable row level security;
alter table public.memories enable row level security;
alter table public.shelves enable row level security;
alter table public.shelf_items enable row level security;
alter table public.recommendations enable row level security;

-- ให้สิทธิ์ backend (service_role)
-- บนโปรเจกต์ reamo สิทธิ์นี้มาจากค่าเริ่มต้นของ Supabase อยู่แล้ว คำสั่งนี้จึงซ้ำซ้อนแต่ไม่เป็นอันตราย
grant select, insert, update, delete on
  public.books,
  public.feelings,
  public.user_books,
  public.memories,
  public.shelves,
  public.shelf_items,
  public.recommendations
to service_role;

commit;
